#!/usr/bin/env node
/**
 * Emits dist/sw.js after `vite build`. Precache everything in dist/ (hashed
 * app shell assets + images from the content pack) plus "/", with a
 * cache-first strategy and an SPA navigation fallback to "/".
 * Output: apps/web/dist/sw.js
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, resolve, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const DIST = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..", "apps", "web", "dist");

function walk(dir, base, acc) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const rel = relative(base, full).replace(/\\/g, "/");
    if (statSync(full).isDirectory()) walk(full, base, acc);
    else acc.push(rel);
  }
  return acc;
}

if (!existsSync(DIST)) {
  console.error("build-precache: dist/ not found. Run the web build first.");
  process.exit(1);
}

const files = walk(DIST, DIST, []).filter((f) => f !== "sw.js");
const urls = ["/", ...files.map((f) => `/${f}`)].sort();
const version = createHash("sha256")
  .update(urls.join("\n"))
  .digest("hex")
  .slice(0, 12);

const sw = `/* Zivvvo offline cache -- generated by tools/zivvvo/build-precache.mjs */
const VERSION = "zv${version}";
const PRECACHE = ${JSON.stringify(urls, null, 0)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(VERSION).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== VERSION).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;

  // SPA navigation: serve the cached shell offline, network-first when online.
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((res) => {
          const copy = res.clone();
          caches.open(VERSION).then((c) => c.put("/", copy));
          return res;
        })
        .catch(() => caches.match("/").then((r) => r || Response.error())),
    );
    return;
  }

  // Same-origin static: cache-first, then network + background fill.
  if (new URL(request.url).origin === self.location.origin) {
    event.respondWith(
      caches.match(request).then(
        (cached) =>
          cached ||
          fetch(request).then((res) => {
            const copy = res.clone();
            caches.open(VERSION).then((c) => c.put(request, copy));
            return res;
          }),
      ),
    );
  }
});
`;

writeFileSync(join(DIST, "sw.js"), sw, "utf8");
console.log(`build-precache: sw.js written (${urls.length} urls, version ${version})`);